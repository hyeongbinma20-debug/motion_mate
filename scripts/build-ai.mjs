import {readFile,writeFile,mkdir} from 'node:fs/promises';
const root=new URL('../',import.meta.url),output=new URL('supabase/functions/bookit-ai/',root);
await mkdir(output,{recursive:true});
const contract=await readFile(new URL('dist/book-info.js',root),'utf8');
const core=(await readFile(new URL('server/ai-core.mjs',root),'utf8')).replace(/^import .*from '..\/dist\/book-info.js';\r?\n/,'');
await writeFile(new URL('handler.js',output),'// Generated by scripts/build-ai.mjs. Edit the shared contracts and server/ai-core.mjs.\n'+contract+'\n'+core);
await writeFile(new URL('index.ts',output),"import {createAIHandler} from './handler.js';\nDeno.serve(createAIHandler({env:(name:string)=>Deno.env.get(name)}));\n");
console.log('Built credential-free Edge Function source: supabase/functions/bookit-ai/');
