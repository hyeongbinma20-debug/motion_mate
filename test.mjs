import assert from 'node:assert/strict';
import {seed,propose,transition,contacts,recommend} from './dist/domain.js';
const d=seed();
const r=propose(d,'u1','b1','b7','교환하고 싶어요');
assert.equal(r.status,'대기 중');assert.deepEqual(contacts(d,r,'u1'),[]);
assert.throws(()=>propose(d,'u1','b3','b7','중복'));
assert.throws(()=>propose(d,'u1','b7','b7','내 책'));
const competing=propose(d,'u3','b1','b0','다른 제안');
assert.throws(()=>transition(d,r.id,'u1','수락됨'));
transition(d,r.id,'u2','수락됨');
assert.equal(competing.status,'거절됨');assert.equal(contacts(d,r,'u1').length,2);assert.deepEqual(contacts(d,r,'u3'),[]);
assert.throws(()=>propose(d,'u3','b1','b2','예약된 책'));
transition(d,r.id,'u1','완료');assert.equal(r.status,'수락됨');
transition(d,r.id,'u1','완료');assert.equal(r.confirmations.length,1);
transition(d,r.id,'u2','완료');assert.equal(r.status,'교환 완료');assert.equal(d.books.find(b=>b.id==='b7').status,'completed');
const rec=recommend(d,d.users[0]);assert(rec.every(b=>b.owner!=='u1'&&b.status==='available'));
const rejected=propose(d,'u3','b3','b2','거절 테스트');transition(d,rejected.id,'u2','거절됨');assert.deepEqual(contacts(d,rejected,'u3'),[]);
const cancelled=propose(d,'u3','b3','b2','취소 테스트');transition(d,cancelled.id,'u3','취소됨');assert.equal(cancelled.status,'취소됨');
assert.deepEqual(JSON.parse(JSON.stringify(d)),d);
console.log('PASS: request, duplicate prevention, ownership, privacy, acceptance, competing closure, reservations, two-sided completion, rejection, cancellation, recommendations, serialization');
